import { useEffect, useState } from "react";
import { Info, Sparkles, X } from "lucide-react";
import { explainMedicine } from "../../api/prescriptionApi";
import { getErrorMessage } from "../../api/getErrorMessage";
import { Spinner } from "./States";

/**
 * "Explain this medicine" - a plain-language description generated from the
 * medicine's stored record.
 *
 * The disclaimer below is rendered by this component, not taken from the
 * generated text, so it is always present whichever engine produced the
 * explanation.
 */
export default function ExplainDialog({ medicine, onClose }) {
  const [state, setState] = useState({ status: "loading" });

  useEffect(() => {
    if (!medicine?.medicine_id) return undefined;
    let cancelled = false;
    setState({ status: "loading" });
    explainMedicine(medicine.medicine_id)
      .then((res) => !cancelled && setState({ status: "ready", data: res.data }))
      .catch((err) => !cancelled && setState({ status: "error", message: getErrorMessage(err) }));
    return () => { cancelled = true; };
  }, [medicine?.medicine_id]);

  if (!medicine) return null;

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div
        className="modal-card picker-card"
        onClick={(e) => e.stopPropagation()}
        role="dialog"
        aria-modal="true"
        aria-label={`About ${medicine.medicine_name}`}
      >
        <div className="picker-header">
          <div className="grow">
            <h3 className="row" style={{ gap: "0.5rem" }}>
              <Sparkles size={17} /> About this medicine
            </h3>
            <p className="picker-rawtext">{medicine.medicine_name}</p>
          </div>
          <button type="button" className="picker-close" onClick={onClose} aria-label="Close">
            <X size={18} />
          </button>
        </div>

        {state.status === "loading" && (
          <div style={{ padding: "var(--s-4) 0" }}>
            <Spinner label="Writing a plain-language summary…" />
          </div>
        )}

        {state.status === "error" && (
          <div className="alert alert-risk">{state.message}</div>
        )}

        {state.status === "ready" && (
          <div className="explain-panel">
            <div className="explain-body">
              {String(state.data.text).split("\n\n").map((para, i) => (
                <p key={i}>{para}</p>
              ))}
            </div>
            {state.data.sections?.length > 0 && (
              <dl className="explain-sections">
                {state.data.sections.map((sec) => (
                  <div key={sec.title}>
                    <dt>{sec.title}</dt>
                    {String(sec.text).split("\n").map((line, i) => (
                      <dd key={i}>{line}</dd>
                    ))}
                  </div>
                ))}
              </dl>
            )}
            {state.data.note && <p className="explain-note">{state.data.note}</p>}
            <p className="explain-source">
              <Info size={11} style={{ verticalAlign: "-1px" }} />{" "}
              {state.data.source === "gemini"
                ? "Generated by Google Gemini from this medicine's stored record."
                : state.data.sections?.length > 0
                  ? "Product details come from our dataset; the ingredient notes are general reference text written for this app."
                  : "Compiled from this medicine's stored record."}
            </p>
          </div>
        )}

        {state.status === "ready" && (
          <div className="alert alert-warn" style={{ marginTop: "var(--s-3)", marginBottom: 0 }}>
            <span className="tiny">{state.data.disclaimer}</span>
          </div>
        )}

        <div className="modal-actions" style={{ marginTop: "var(--s-4)" }}>
          <button type="button" className="btn btn-secondary" onClick={onClose}>Close</button>
        </div>
      </div>
    </div>
  );
}
